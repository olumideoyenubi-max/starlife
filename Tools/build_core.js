// Builds Assets/Resources/starlife_core.txt from the artifact's script (Tools/artifact-script.js):
// everything before the page event handlers, plus host shims so it runs without a browser.
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'artifact-script.js'), 'utf8').split('\n');
const end = src.findIndex(l => l.startsWith('// ---------- events ----------'));
if (end < 0) throw new Error('events marker not found');
const head = `// GENERATED by Tools/build_core.js from the Starlife Suite artifact. Do not edit by hand.
var localStorage = { getItem: function (k) { return host.get(k); }, setItem: function (k, v) { host.set(k, v); } };
var window = {}, document = {}, performance = { now: function () { return Date.now(); } };
function setTimeout(f) { return 0; } function clearTimeout() {}
`;
const foot = fs.readFileSync(path.join(__dirname, 'core_api.js'), 'utf8');
const out = head + src.slice(1, end).join('\n') + '\n' + foot;
fs.writeFileSync(path.join(__dirname, '..', 'Assets', 'Resources', 'starlife_core.txt'), out);
console.log('core written', out.length, 'bytes');
